using System.Text.Json;
using System.Globalization;
using CollectionsService.Models;
using CollectionsService.Services.Ai;
using Microsoft.Extensions.Options;
using Npgsql;
using NpgsqlTypes;

namespace CollectionsService.Services;

/// <summary>
/// PostgreSQL-backed implementation of the collections API. Collections are
/// stored as rows, with their cards serialized into a JSONB column.
/// </summary>
public sealed class PostgresService : CollectionsApiInterface
{
    private const string TableName = "collections";
    private static readonly JsonSerializerOptions JsonOptions = new()
    {
        PropertyNameCaseInsensitive = true
    };

    private readonly string _connectionString;
    private readonly EmbeddingService _embeddingService;

    public PostgresService(
        IOptions<CollectionsDBSettings> settings,
        EmbeddingService embeddingService)
    {
        _connectionString = settings.Value.ConnectionString;
        _embeddingService = embeddingService;

        using var connection = OpenConnection();

        using var vectorDbCommand = new NpgsqlCommand($"""
            CREATE EXTENSION IF NOT EXISTS vector;
            """, connection);

        using var command = new NpgsqlCommand($"""
            CREATE TABLE IF NOT EXISTS {TableName} (
                ordinal BIGINT GENERATED BY DEFAULT AS IDENTITY,
                id TEXT PRIMARY KEY,
                title TEXT NOT NULL,
                description TEXT NOT NULL,
                emoji TEXT NOT NULL,
                cards JSONB NOT NULL DEFAULT '[]'::jsonb,
                embedding VECTOR(768)
            );
            """, connection);
            // TODOO: check this command and the vector size
        //                 embedding VECTOR(1536) GENERATED ALWAYS AS (cards_embedding(cards)) STORED
        vectorDbCommand.ExecuteNonQuery();
        command.ExecuteNonQuery();
    }

    public List<Collection> GetAsync()
    {
        using var connection = OpenConnection();
        using var command = new NpgsqlCommand(
            $"SELECT id, title, description, emoji, cards FROM {TableName} ORDER BY ordinal",
            connection);
        using var reader = command.ExecuteReader();

        var collections = new List<Collection>();
        while (reader.Read())
        {
            collections.Add(ReadCollection(reader));
        }

        return collections;
    }

    public Collection? GetAsync(string id)
    {
        using var connection = OpenConnection();
        using var command = new NpgsqlCommand(
            $"SELECT id, title, description, emoji, cards FROM {TableName} WHERE id = @id",
            connection);
        command.Parameters.AddWithValue("id", id);

        using var reader = command.ExecuteReader();
        return reader.Read() ? ReadCollection(reader) : null;
    }

    public void CreateAsync(Collection newCollection)
    {
        using var connection = OpenConnection();
        using var command = new NpgsqlCommand($"""
            INSERT INTO {TableName} (id, title, description, emoji, cards)
            VALUES (@id, @title, @description, @emoji, @cards)
            """, connection);
        AddCollectionParameters(command, newCollection);
        command.ExecuteNonQuery();
    }

    public void UpdateAsync(string id, Collection updatedCollection)
    {
        using var connection = OpenConnection();
        using var command = new NpgsqlCommand($"""
            INSERT INTO {TableName} (id, title, description, emoji, cards)
            VALUES (@id, @title, @description, @emoji, @cards)
            ON CONFLICT (id) DO UPDATE SET
                title = EXCLUDED.title,
                description = EXCLUDED.description,
                emoji = EXCLUDED.emoji,
                cards = EXCLUDED.cards
            """, connection);
        updatedCollection.Id = id;
        AddCollectionParameters(command, updatedCollection);
        command.ExecuteNonQuery();
    }

    public void RemoveAsync(string id)
    {
        using var connection = OpenConnection();
        using var command = new NpgsqlCommand(
            $"DELETE FROM {TableName} WHERE id = @id", connection);
        command.Parameters.AddWithValue("id", id);
        command.ExecuteNonQuery();
    }

    public void CreateCard(string id, Card newCard)
    {
        var collection = GetAsync(id);
        if (collection is null)
        {
            return;
        }

        collection.Cards.Add(newCard);
        UpdateAsync(id, collection);
    }

    public void DeleteCard(string collectionId, string cardId)
    {
        var collection = GetAsync(collectionId);
        if (collection is null)
        {
            return;
        }

        collection.Cards.RemoveAll(card => card.Id == cardId);
        UpdateAsync(collectionId, collection);
    }

    // TODO: move this to the controller and replace the query with embeddings
    public List<Card> SearchCards(string query)
    {
        ArgumentException.ThrowIfNullOrWhiteSpace(query);

        // The existing API and service interface are synchronous, so bridge the
        // async embedding HTTP call here while preserving that interface.
        var embedding = _embeddingService.GetEmbeddingAsync(query).GetAwaiter().GetResult();
        if (embedding.Count != 768)
        {
            throw new InvalidOperationException(
                $"Expected a 768-dimensional embedding, but received {embedding.Count} values.");
        }

        var vectorLiteral = "[" + string.Join(
            ",",
            embedding.Select(value => value.ToString("R", CultureInfo.InvariantCulture))) + "]";

        using var connection = OpenConnection();
        using var command = new NpgsqlCommand($"""
            SELECT card_item.value::text
            FROM {TableName} AS collection
            CROSS JOIN LATERAL jsonb_array_elements(collection.cards) AS card_item(value)
            WHERE COALESCE(card_item.value->'Embedding', card_item.value->'embedding') IS NOT NULL
              AND COALESCE(card_item.value->'Embedding', card_item.value->'embedding') <> 'null'::jsonb
            ORDER BY COALESCE(
                card_item.value->'Embedding',
                card_item.value->'embedding'
            )::text::vector <-> @embedding::vector
            LIMIT 5
            """, connection);
        command.Parameters.AddWithValue("embedding", vectorLiteral);

        using var reader = command.ExecuteReader();
        var cards = new List<Card>();
        while (reader.Read())
        {
            var card = JsonSerializer.Deserialize<Card>(reader.GetString(0), JsonOptions);
            if (card is not null)
            {
                cards.Add(card);
            }
        }

        return cards;
    }

    private NpgsqlConnection OpenConnection()
    {
        var connection = new NpgsqlConnection(_connectionString);
        connection.Open();
        return connection;
    }

    private static Collection ReadCollection(NpgsqlDataReader reader) => new()
    {
        Id = reader.GetString(0),
        Title = reader.GetString(1),
        Description = reader.GetString(2),
        Emoji = reader.GetString(3),
        Cards = JsonSerializer.Deserialize<List<Card>>(reader.GetString(4), JsonOptions) ?? new()
    };

    private static void AddCollectionParameters(NpgsqlCommand command, Collection collection)
    {
        command.Parameters.AddWithValue("id", collection.Id);
        command.Parameters.AddWithValue("title", collection.Title);
        command.Parameters.AddWithValue("description", collection.Description);
        command.Parameters.AddWithValue("emoji", collection.Emoji);
        command.Parameters.Add(new NpgsqlParameter("cards", NpgsqlDbType.Jsonb)
        {
            Value = JsonSerializer.Serialize(collection.Cards, JsonOptions)
        });
    }
}
